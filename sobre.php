            <h2>O que é o TEA?</h2>

            <p>
                O Transtorno do Espectro Autista (TEA) é uma condição do
                <span class="tooltip-termo" onclick="toggleTooltip(this)">
                    neurodesenvolvimento
                    <span class="tooltip-text">
                        Processo de crescimento e organização do sistema nervoso, responsável por moldar e estruturar habilidades motoras, cognitivas, sensoriais, comunicativas e emocionais.
                    </span>
                </span>
                que influencia a forma como a pessoa se comunica, interage socialmente e percebe o mundo ao seu redor. Cada pessoa autista é única, possuindo características, habilidades e necessidades próprias. O TEA acompanha a pessoa ao longo da vida, fazendo parte da sua forma de compreender o mundo. Com apoio, informação e inclusão, pessoas autistas podem desenvolver seu potencial, conquistar autonomia e ter qualidade de vida.
            </p>

