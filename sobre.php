<section id="niveis-suporte" class="niveis-suporte">

    <div class="titulo">

    <h2>Níveis de suporte</h2>

    <p>
        Os níveis de suporte do Transtorno do Espectro Autista (TEA) indicam a quantidade de apoio que uma pessoa pode necessitar em seu dia a dia. Eles fazem parte da avaliação diagnóstica e ajudam os profissionais a compreender as necessidades individuais de cada pessoa, contribuindo para um acompanhamento mais adequado.
    </p>

</div>


<details class="nivel1">

       <summary>Nível 1 — Necessita de apoio</summary>

    <p>
        Pessoas com TEA nível 1 geralmente possuem maior autonomia nas atividades diárias, mas podem apresentar dificuldades em situações sociais, como iniciar ou manter conversas, compreender regras sociais e lidar com mudanças inesperadas. Algumas pessoas podem desenvolver estratégias para esconder ou adaptar suas características sociais, um comportamento conhecido como masking.
    </p>

    <p class="lembrete">
        💙 <strong>Vale lembrar:</strong> Ter maior autonomia não significa ser <strong>"menos autista"</strong>. Cada pessoa possui características e necessidades de apoio diferentes.
    </p>
</details>


<details class="nivel2">

    <summary>Nível 2 — Necessita de apoio substancial</summary>

    <p>
        Pessoas com TEA nível 2 apresentam dificuldades mais perceptíveis na comunicação e na interação social, podendo precisar de apoio frequente para realizar atividades do cotidiano e participar de diferentes ambientes.
</p>
    </p>

    <p>
        Algumas pessoas podem apresentar
        <span class="tooltip-termo" onclick="toggleTooltip(this)">
            comorbidades
            <span class="tooltip-text">
                Outras condições que podem ocorrer junto ao TEA, como ansiedade, TDAH, epilepsia, distúrbios do sono ou dificuldades de aprendizagem.
            </span>
        </span>,
        sendo importante um acompanhamento individualizado.
    </p>

</details>

<!-- NÍVEL 3 -->

<details class="nivel3">

    <summary>Nível 3 — Necessita de apoio muito substancial</summary>

    <p>
        Pessoas com TEA nível 3 apresentam necessidade de apoio intenso e contínuo em diversas áreas da vida, especialmente relacionadas à comunicação, interação social e atividades do cotidiano.
    </p>

    <p>
        Podem apresentar dificuldades significativas na comunicação verbal ou não verbal, maior necessidade de auxílio para iniciar interações e maior dificuldade diante de mudanças na rotina.
    </p>

    <p>
        Também podem apresentar comorbidades,tornando essencial um acompanhamento conforme suas necessidades.
    </p>

</details>



<div class="info-destaque">

    <h4>💡 Entenda os níveis de suporte</h4>

    <p>
        Os níveis de suporte não representam uma classificação de "maior" ou "menor" valor entre pessoas autistas. Eles indicam a quantidade de apoio que pode ser necessária em determinado momento da vida.
    </p>

    <p>
        As necessidades de suporte podem variar conforme o ambiente, as experiências, o desenvolvimento e os recursos disponíveis para cada pessoa.
    </p>

</div>

