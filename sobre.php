<h2>Primeiros sinais</h2>

<p>
    Os sinais do TEA podem ser percebidos nos primeiros anos de vida, mas se manifestam de formas diferentes em cada pessoa. A observação atenta do desenvolvimento da criança é fundamental para identificar possíveis sinais de alerta
</p>

<div class="timeline-item">
    <span class="circulo">👶</span>
    <div>
        <h3>0 a 6 meses</h3>

        <p>
            Nesse período, os sinais costumam ser sutis e estão relacionados à ausência de alguns comportamentos esperados para o desenvolvimento típico. Entre eles estão o menor contato visual, a ausência do
            <span class="tooltip-termo" onclick="toggleTooltip(this)">
                sorriso social
                <span class="tooltip-text">
                    É quando o bebê sorri espontaneamente em resposta ao rosto, à voz ou à interação com outra pessoa.
                </span>
            </span>,
            pouca resposta às interações sociais, dificuldade em acompanhar o olhar e as expressões faciais dos cuidadores, além de menor interesse em interações com as pessoas ao seu redor.
        </p>

    </div>
</div>

<div class="timeline-item">
    <span class="circulo">👦</span>
    <div>

        <h3>6 a 12 meses</h3>

        <p>
            Os principais sinais nessa fase estão relacionados à comunicação social, à interação e ao comportamento. Entre eles estão pouco ou nenhum contato visual, ausência de resposta ao nome, pouca interação social, dificuldade em imitar sons e gestos,
            <span class="tooltip-termo" onclick="toggleTooltip(this)">
                balbucio
                <span class="tooltip-text">
                    Sons repetitivos produzidos pelo bebê, como "ba-ba", "ma-ma" ou "da-da", importantes para o desenvolvimento da linguagem.
                </span>
            </span>
            reduzido ou ausente e interesse limitado por brinquedos ou pessoas.
        </p>

    </div>
</div>

<div class="timeline-item">
    <span class="circulo">👧</span>
    <div>

        <h3>2 a 5 anos</h3>

        <p>
            Entre os 2 e 5 anos, os sinais do Transtorno do Espectro Autista (TEA) costumam se tornar mais perceptíveis, principalmente devido ao aumento das interações sociais e do desenvolvimento da linguagem. Nessa fase, os comportamentos podem ser observados em três áreas principais.
        </p>

        <h4>Comunicação e Linguagem</h4>

        <p>
            Atraso no desenvolvimento da fala ou ausência de linguagem verbal, repetição frequente de palavras, frases ou trechos de programas de televisão
            (
            <span class="tooltip-termo" onclick="toggleTooltip(this)">
                ecolalia
                <span class="tooltip-text">
                    Repetição de palavras, frases ou sons que a criança ouviu anteriormente.
                </span>
            </span>
            ),
            perda de habilidades já adquiridas, dificuldade para iniciar ou manter conversas e para compreender ou responder a comandos verbais simples.
        </p>

        <h4>Interação Social</h4>

        <p>
            Pouco contato visual durante as interações, dificuldade ou desinteresse em brincar com outras crianças, preferência por brincar sozinho, pouca participação em
            <span class="tooltip-termo" onclick="toggleTooltip(this)">
                brincadeiras de faz de conta
                <span class="tooltip-text">
                    Brincadeiras em que a criança usa a imaginação, como fingir que cozinha, cuida de uma boneca, brinca de médico ou dirige um carrinho.
                </span>
            </span>,
            dificuldade para compartilhar interesses ou emoções e nem sempre responder quando chamado pelo próprio nome.
        </p>

        <h4>Comportamentos e Interesses</h4>

        <p>
            Movimentos repetitivos, como balançar as mãos, o corpo ou andar na ponta dos pés, interesses restritos, resistência a mudanças na rotina, necessidade de seguir padrões específicos, hábito de alinhar ou organizar objetos e sensibilidade aumentada ou reduzida a sons, luzes, texturas, cheiros, toques ou determinados alimentos.
        </p>

    </div>
    
</div>
